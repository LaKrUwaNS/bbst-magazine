export function getFallbackWriterBySlug(slug: string): WriterDetailData | null {
  const normalized = slug.toLowerCase().trim();
  if (FALLBACK_WRITER_DETAILS[normalized]) {
    return FALLBACK_WRITER_DETAILS[normalized];
  }

  // Check matching in FALLBACK_WRITERS
  const found = FALLBACK_WRITERS.find((w) => w.slug === normalized || w.id === normalized);
  if (!found) return null;

  return {
    id: found.id,
    name: found.name,
    slug: found.slug,
    bio: `${found.name} is an active student researcher and contributor to the BBST Student Magazine at Uva Wellassa University.`,
    shortBio: found.shortBio,
    profileImageUrl: found.profileImageUrl,
    department: found.department,
    academicYear: found.academicYear,
    role: found.role,
    expertise: found.expertise,
    website: found.website,
    email: `${found.slug}@bbst.uwu.ac.lk`,
    socialLinks: found.socialLinks,
    isFeatured: found.isFeatured,
    publishedArticlesCount: found.publishedArticlesCount,
    articles: [],
  };
}
